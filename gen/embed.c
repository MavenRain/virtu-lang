/* Writes a C file that holds the bytes of the domain files, in order.
   Usage: tcc -run gen/embed.c domain/domain.lang [MORE.lang ...] build/domain.c
   A newline goes between two files. SHARED by the tcc kits. */
#include <stdio.h>

static void put(FILE *out, int c, size_t *count) {
  fprintf(out, "%s0x%02x,", *count % 12 == 0 ? "\n  " : " ", (unsigned)c);
  (*count)++;
}

static int copy(const char *name, FILE *out, size_t *count) {
  FILE *in = fopen(name, "rb");
  if (in == NULL) return 0;
  int c = fgetc(in);
  while (c != EOF) {
    put(out, c, count);
    c = fgetc(in);
  }
  int ok = ferror(in) == 0;
  fclose(in);
  return ok;
}

int main(int argc, char **argv) {
  if (argc < 3) {
    fputs("usage: embed IN... OUT\n", stderr);
    return 2;
  }
  const char *target = argv[argc - 1];
  FILE *out = fopen(target, "wb");
  int ok = out != NULL;
  size_t count = 0;
  if (ok) {
    fputs("/* Generated by gen/embed.c from", out);
    for (int i = 1; i < argc - 1; i++) fprintf(out, " %s", argv[i]);
    fputs(". Do not edit. */\n#include <stddef.h>\n\nconst unsigned char domain_source[] = {", out);
  }
  for (int i = 1; ok && i < argc - 1; i++) {
    if (i > 1) put(out, '\n', &count);
    ok = copy(argv[i], out, &count);
  }
  if (ok) fprintf(out, "\n  0x00\n};\nconst size_t domain_source_len = %lu;\n", (unsigned long)count);
  if (out != NULL) ok = ferror(out) == 0 && fclose(out) == 0 && ok;
  if (!ok) {
    fprintf(stderr, "embed: cannot write %s\n", target);
    remove(target);
  }
  return ok ? 0 : 2;
}
